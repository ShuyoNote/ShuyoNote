// 「取回附件字节失败」→ **能行动的一句话**（2026-09-19，社区缺陷帖 #6 / GitCode issue #6）。
//
// ## 为什么单独一个文件、且不带任何 import
//
// 它是个**纯字符串分类**：输入是 `download_attachment` 的报错原文，输出是给用户看的一句话。
// 不 import `api` / store / Tauri —— 这样单测不需要浏览器或 Tauri 环境（与 `columnsText` 那类一致）。
//
// ## 为什么需要它（这次的真实教训）
//
// 用户在文件管理器里点一个 `.md`，弹出的是原文：
//
//     取回文件失败：服务端返回 404 Not Found
//
// 两处不好：① 读不出"我该怎么办"；② **这个状态下"再试一次"永远不会成功**——
// 字节既不在本机（附件目录里没有），也不在服务器（这个空间从来没配置过同步、从未上传）。
// 对这类"取不回"与"暂时取不回"必须给不同的下一步，否则界面在**承诺一件做不到的事**。
//
// 分支的判据来自 `src-tauri/src/sync.rs` 的真实文案（别按英文猜）：
//   · `请先配置同步服务器` —— `download_attachment` 在 `server_url` 为空时直接返回这句；
//   · `服务端返回 <状态码>` —— `download_one_attachment` 对非成功响应的原话（404 最常见）；
//   · 其余（超时 / 连接失败 / IO）—— 属于可重试。
export function attachmentFetchHint(err: unknown): string {
  const raw = String((err as { message?: unknown } | null)?.message ?? err ?? "").trim();
  if (!raw) return "取回文件失败（没拿到原因）——本机没有这份字节时需要在原电脑上重新导入。";

  // ① 这个空间没有同步配置：字节只可能在导入它的那台机器上
  if (raw.includes("请先配置同步服务器")) {
    return "这个空间没有配置同步服务器，附件只存在导入它的那台电脑上，无法从服务器取回；只能在原电脑上重新导入这个文件。";
  }
  // ② 服务器上没有这份字节（导入时没上传成功，或被预算刹车挡掉）
  if (/服务端返回\s*404/.test(raw)) {
    return "服务器上没有这份字节（导入时可能没上传成功），本机也没有留副本；只能从原文件重新导入。";
  }
  // ③ 鉴权/权限：能修
  if (/服务端返回\s*(401|403)/.test(raw)) {
    return "服务器拒绝了这次取回（登录状态或空间权限）——请到同步面板重新登录，或检查这个空间的同步配置。";
  }
  // ④ 服务端/网络暂时故障：可重试
  if (/服务端返回\s*5\d\d/.test(raw) || /timeout|timed out|error sending request|connect|连接/i.test(raw)) {
    return `这一步是网络或服务器暂时失败，可以直接重试：${raw}`;
  }
  // ⑤ 未知：原样带上，不许吞掉原因（这是本仓"错误不许被吞"那条纪律）
  return `取回文件失败：${raw}`;
}
