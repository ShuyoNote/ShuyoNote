// 派生文本落库前的统一归一化 —— **只在管道层施加一次**，抽取器不要自己做。
// 契约见 docs/plans/2026-09-17-knowledge-base-ai-coverage-plan.md §15.3（第 10 条不变量）。
//
// ## 要修的是什么（Mac 侧在真 PDF 上实测）
// 用仓库自带 Chrome 打印中文 HTML 成 PDF，抽出来的字里 `第⼀段` 用的是
// **U+2F00「康熙部首 ⼀」**，而不是 **U+4E00「一」**：
//
//     "第⼀段".includes("第一段")  ===  false     // ⇒ 用户搜「第一段」搜不到
//
// 这类**兼容形**不是 PDF 独有的：PDF 的 ToUnicode 表、Office 的兼容表、VLM 的输出都可能带。
// 所以修法必须**统一**，否则三份抽取器各写各的（正是 §12.3 分家最怕的"三套都能跑但结果不一致"）。
//
// ## 为什么是**窄口径**，而不是直接上 `normalize("NFKC")`
// 我第一版就是全量 NFKC，**跑测试才发现附带影响比预想大**：
//
//     NFKC("，")  ===  ","      ← U+FF0C 全角逗号被转成 ASCII 逗号
//     NFKC("。")  ===  "。"      ← U+3002 句号**不变**（它不是兼容字符）
//     ⇒ "第一段，第二段。" → "第一段,第二段。"   ← **同一句里标点风格混杂**
//
// 对中文文档，这比"① → 1"显眼得多，而且是**可见的质量退化**，不是净收益。
// 所以这里改成**只折叠会造成检索漏字的兼容表意字区间**——那是本次要修的那个 bug，
// 且**零附带影响**。
//
// ## 刻意**不**折叠的（以及为什么）
// - **全角标点 / 全角字母数字**（`，１２３ＡＢＣ`）：折叠它们会把中文标点改成 ASCII，
//   收益（`１２３` 能搜到 `123`）远小于"派生文本读起来不像中文"的代价。
// - 其余兼容形（带圈数字、连字等）：同上。
// ⇒ 若将来确有需要，应做成**可配置项**而不是默认行为；默认值保持"最小惊讶"。
//
// ## 为什么敢改文本
// 因为派生文本**本来就是可重建的缓存、不是事实源**（方案 §6.1：只读、可重建、不进同步/备份/导出，
// **以原件为准**）。原件字节始终在附件里，改的是我们自己的派生副本。

/**
 * 只包含**兼容表意字**的区间：它们经 NFKC 会映射到统一表意字。
 *
 * - `U+2E80–U+2EFF` CJK 部首补充
 * - `U+2F00–U+2FDF` **康熙部首**（本次实测命中的那一类）
 * - `U+F900–U+FAFF` CJK 兼容表意字
 * - `U+2F800–U+2FA1F` CJK 兼容表意字补充
 */
const COMPAT_IDEOGRAPH = /[\u2E80-\u2EFF\u2F00-\u2FDF\uF900-\uFAFF\u{2F800}-\u{2FA1F}]/gu;

/**
 * 派生文本落库前的统一归一化：**只折叠兼容表意字**。
 *
 * ⚠️ **抽取器不要调用它**（不要在自己的 `normalizeText` 里加这一步）：
 * 一处归一化才有"下游不可能忘"的性质；两处归一化会让人以为别处也做了。
 */
export function normalizeForStore(text: string): string {
  return text.replace(COMPAT_IDEOGRAPH, (ch) => ch.normalize("NFKC"));
}

/** 查询侧必须与存储侧**用同一个折叠口径** —— 否则"索引归一了、查询没归一"照样搜不到。 */
export function normalizeForMatch(text: string): string {
  return text.replace(COMPAT_IDEOGRAPH, (ch) => ch.normalize("NFKC"));
}
